TSharedRef<IDetailCustomization> FPWGameplayAbility_DetailCustomization::MakeInstance()
{
	return MakeShareable(new FPWGameplayAbility_DetailCustomization);
}

void FPWGameplayAbility_DetailCustomization::CustomizeDetails(IDetailLayoutBuilder& DetailBuilder)
{
	DetailBuilder.GetObjectsBeingCustomized(SelectedObjects);

	IDetailCategoryBuilder& Cat = DetailBuilder.EditCategory("Tags");
	Cat.AddCustomRow(FText::FromString("Generate Ability Tags"))
	.WholeRowContent()
	[
		SNew(SButton)
		.Text(FText::FromString("Generate Ability Tags And Assign Defaults"))
		.OnClicked(FOnClicked::CreateSP(this, &FPWGameplayAbility_DetailCustomization::OnGenerateTagsClicked))
	];
}

FReply FPWGameplayAbility_DetailCustomization::OnGenerateTagsClicked()
{
	for (TWeakObjectPtr<UObject> Obj : SelectedObjects)
	{
		if (UPWGameplayAbilityBase* GA = Cast<UPWGameplayAbilityBase>(Obj.Get()))
		{
			const FString IdentityTag = GA->GetIdentityTagName();
			for (const FString& Tag : {IdentityTag, IdentityTag + TEXT(".Cooldown")})
				if (!UGameplayTagsManager::Get().RequestGameplayTag(*Tag, false).IsValid())
					IGameplayTagsEditorModule::Get().AddNewGameplayTagToINI(Tag, TEXT("Auto-generated by GASCore"));

			GA->GenerateIdentityTag();
			FindOrCreateAbilityData(GA);
		}
	}
	return FReply::Handled();
}

void FPWGameplayAbility_DetailCustomization::FindOrCreateAbilityData(const UPWGameplayAbilityBase* GA)
{
	UClass* AbilityClass = GA->GetClass();
	if (!AbilityClass->ClassGeneratedBy) return;

	UPWAbilityDataAsset* AbilityData = nullptr;

	TArray<FAssetData> Assets;
	FAssetRegistryModule::GetRegistry().GetAssetsByClass(UPWAbilityDataAsset::StaticClass()->GetClassPathName(), Assets, true);
	for (const FAssetData& Asset : Assets)
	{
		UPWAbilityDataAsset* Existing = Cast<UPWAbilityDataAsset>(Asset.GetAsset());
		if (Existing && Existing->Ability.AbilityClass == AbilityClass)
		{
			AbilityData = Existing;
			break;
		}
	}

	if (!AbilityData)
	{
		FString AssetName = AbilityClass->ClassGeneratedBy->GetName();
		if (AssetName.StartsWith(TEXT("BP_"))) { AssetName.RightChopInline(3); }
		if (AssetName.StartsWith(TEXT("GA_"))) { AssetName.RightChopInline(3); }
		AssetName = TEXT("DA_") + AssetName;

		const FString Folder = FPackageName::GetLongPackagePath(AbilityClass->GetPackage()->GetName());
		AbilityData = LoadObject<UPWAbilityDataAsset>(nullptr, *(Folder / AssetName + TEXT(".") + AssetName), nullptr, LOAD_NoWarn | LOAD_Quiet);
		if (!AbilityData)
			AbilityData = Cast<UPWAbilityDataAsset>(FAssetToolsModule::GetModule().Get().CreateAsset(AssetName, Folder, UPWAbilityDataAsset::StaticClass(), nullptr));
	}

	if (!AbilityData) return;

	AbilityData->Modify();
	AbilityData->Ability.Tag = GA->AbilityTag;
	AbilityData->Ability.AbilityClass = AbilityClass;
	AbilityData->MarkPackageDirty();
}